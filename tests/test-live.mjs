import { chromium } from 'playwright';
const URL = 'https://orisade.github.io/petanque-ofer-60/';
const errors = [];
const b = await chromium.launch({ channel: 'chrome', headless: true });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
p.on('console', m => m.type() === 'error' && errors.push(m.text()));
p.on('pageerror', e => errors.push(String(e)));
p.on('requestfailed', r => errors.push('FAILED: ' + r.url().slice(0, 70)));
await p.goto(URL, { waitUntil: 'load', timeout: 30000 });
await p.waitForSelector('text=Jouer', { timeout: 15000 });
await p.click('#start-btn');
await p.waitForTimeout(2200);
await p.mouse.move(640, 420);
await p.mouse.down(); await p.waitForTimeout(520); await p.mouse.up();
await p.waitForTimeout(3000);
console.log('phase:', await p.evaluate(() => window.__game.phase));
console.log('balls on court:', await p.evaluate(() => window.__balls.length));
console.log('perk rows:', await p.locator('#perk-bar button').count());
await p.screenshot({ path: 'shot-live.png' });
console.log('ERRORS:', errors.length ? errors : 'none');
await b.close();
