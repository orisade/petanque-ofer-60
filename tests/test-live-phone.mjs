import { chromium, devices } from 'playwright';
const errors = [];
const b = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await b.newContext({ ...devices['iPhone 13'] });
const p = await ctx.newPage();
p.on('console', m => m.type() === 'error' && errors.push(m.text()));
p.on('pageerror', e => errors.push(String(e)));
await p.goto('https://orisade.github.io/petanque-ofer-60/', { waitUntil: 'load', timeout: 30000 });
await p.waitForSelector('text=Jouer', { timeout: 15000 });
await p.screenshot({ path: 'shot-live-phone-start.png' });
await p.click('#start-btn');
await p.waitForTimeout(1500);
await p.mouse.move(195, 420); await p.mouse.down(); await p.waitForTimeout(400); await p.mouse.up();
await p.waitForTimeout(3000);
console.log('perk rows (collapsed):', await p.locator('#perk-bar button').count());
console.log('chip:', (await p.textContent('#perk-bar button.perk-toggle')).trim());
console.log('balls:', await p.evaluate(() => window.__balls.length));
await p.screenshot({ path: 'shot-live-phone.png' });
console.log('ERRORS:', errors.length ? errors : 'none');
await b.close();
